FEATURES_BY_ID: dict[str, FeatureSpec] = {feature.feature_id: feature for feature in FEATURES}
FEATURES_BY_NAME: dict[str, FeatureSpec] = {feature.name: feature for feature in FEATURES}

# Column names in registry (computation) order — this is the canonical
# column order of every persisted feature dataset.
FEATURE_COLUMNS: tuple[str, ...] = tuple(feature.name for feature in FEATURES)


def feature_ids() -> tuple[str, ...]:
    """Return all feature IDs in computation order."""
    return tuple(feature.feature_id for feature in FEATURES)


def feature_count() -> int:
    """Number of registered MVP features (52)."""
    return len(FEATURES)


def max_lookback() -> int:
    """Largest lookback across all features (drives warm-up requirements)."""
    return max(feature.lookback for feature in FEATURES)


def required_source_columns() -> frozenset[str]:
    """Union of every source column consumed by feature computation."""
    return frozenset(column for feature in FEATURES for column in feature.inputs)
