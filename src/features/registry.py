"""Feature registry — the single source of truth for all MVP features.

Every feature is declared here with the exact metadata required by the
milestone (FEATURE_CATALOG.md is the reference specification table):

- ``feature_id``  — stable identifier, e.g. ``RET-01``
- ``name``        — column name in the persisted feature dataset
- ``category``    — approved category (blueprint section 3)
- ``version``     — per-feature version; bumped when the definition changes
- ``formula``     — human-readable mathematical definition
- ``inputs``      — source columns consumed by the computation
- ``lookback``    — maximum lookback window (warm-up rows)
- ``output_type`` — pandas dtype of the output column
- ``normalization`` — scaling requirement (all ``none`` for MVP: returns,
  ratios and bounded indicators are already normalized)
- ``leakage``     — documented leakage risk (all ``none``: every feature
  uses only data available at or before timestamp T)
- ``expected_range`` — documented range for bounded-output validation

Computation lives in :mod:`src.features.compute`; this module contains
only declarative metadata, so registry and math stay independently
testable (blueprint sections 6/17).
"""

